def build_transformer_lstm(hp):
    sequence_length = 10
    num_features = 4

    # Hyperparameter tuning
    num_heads = hp.Int('num_heads', min_value=2, max_value=6, step=1, default=4)
    key_dim = hp.Int('key_dim', min_value=32, max_value=128, step=16, default=64)
    lstm_units = hp.Int('lstm_units', min_value=32, max_value=128, step=32, default=64)

    # Define inputs
    inputs = layers.Input(shape=(sequence_length, num_features))

    # Transformer Multi-Head Attention
    attention_output = layers.MultiHeadAttention(num_heads=num_heads, key_dim=key_dim)(inputs, inputs)
    attention_output = layers.LayerNormalization(epsilon=1e-6)(attention_output)

    # LSTM Layers
    lstm_output = layers.LSTM(units=lstm_units, return_sequences=True)(attention_output)
    lstm_output = layers.LSTM(units=lstm_units)(lstm_output)

    # Output layer (Magnitude prediction)
    outputs = layers.Dense(1)(lstm_output)

    # Define model
    model = Model(inputs=inputs, outputs=outputs)

    # Compile model
    model.compile(optimizer=tf.keras.optimizers.Adam(), loss='mse', metrics=['mae'])

    return model

